def _front_matter(path):
    """The YAML front matter of a MyST page, or {}."""
    import yaml
    text = path.read_text(encoding='utf-8')
    if not text.startswith('---\n'):
        return {}
    return yaml.safe_load(text[4:text.index('\n---', 4)]) or {}


def _latex_documents():
    import datasheet
    result = []
    for name, title in _GUIDES:
        meta = _front_matter(_HERE / name / 'index.md')
        if 'revision' in meta:
            author = f'Jetperch LLC, revision {meta["revision"]} ({meta["date"]})'
            pdf = name.rsplit('/', 1)[-1]
            result.append((f'{name}/index', f'{pdf}_users_guide.tex', title, author,
                           'manual', True))
    for model, title in _DATASHEETS:
        if (datasheet.DATASHEET_DIR / f'{model}.yaml').exists():
            data, _ = datasheet.load(model)
            author = f'Jetperch LLC, revision {data["revision"]}'
            result.append((f'products/datasheets/{model}', f'{model}_datasheet.tex', title, author,
                           'howto', False))
    return result


latex_documents = [] if _ARCHIVE else _latex_documents()


def _switcher_url(name):
    return f'/archive/{name}/versions.json'


def _page_context(app, pagename, templatename, context, doctree):
    """Give project pages their own version switcher (owned pages have none)."""
    if _ARCHIVE:
        name, match = ARCHIVE_PROJECT, ARCHIVE_TAG
    else:
        parts = pagename.split('/')
        if len(parts) < 3 or parts[0] != 'software' or parts[1] not in PROJECTS:
            return
        name, match = parts[1], 'latest'
    context['theme_switcher'] = {'json_url': _switcher_url(name), 'version_match': match}


def versions(name, project, archives):
    """The PyData version switcher entries for one project."""
    entries = [{'name': 'latest', 'version': 'latest', 'url': f'/software/{name}/',
                'preferred': True}]
    entries += [{'name': tag, 'version': tag, 'url': f'/archive/{name}/{tag}/'}
                for tag in archives.get(name, [])]
    if 'rtd' in project:
        entries.append({'name': 'older (Read the Docs)', 'version': 'rtd', 'url': project['rtd']})
    return entries


def _write_versions(app, exception):
    if exception or _ARCHIVE or app.builder.format != 'html':
        return
    archives = load_archives()
    for name, p in PROJECTS.items():
        path = pathlib.Path(app.outdir) / _switcher_url(name).lstrip('/')
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(versions(name, p, archives), indent=2) + '\n')


def _write_llms_txt(app, exception):
    """Index of the guides and raw datasheet data for LLM tools (llmstxt.org)."""
    if exception or _ARCHIVE or app.builder.format != 'html':
        return
    import datasheet
    lines = ['# Joulescope Documentation', '',
             '> User\'s guides, datasheets and software documentation for Joulescope',
             '> precision DC energy analyzers.', '', '## Datasheets (YAML)', '']
    for model, title in _DATASHEETS:
        if (datasheet.DATASHEET_DIR / f'{model}.yaml').exists():
            lines.append(f'- [{title}]({BASE_URL}products/datasheets/{model}.yaml): '
                         f'specification values, format at '
                         f'{BASE_URL}products/datasheets/format.html')
    lines += ['', "## User's guides", '']
    for name, title in _GUIDES:
        if (_HERE / name / 'index.md').exists():
            lines.append(f'- [{title}]({BASE_URL}{name}/index.html)')
    lines += ['', '## Software', '']
    lines += [f'- [{p["title"]}]({BASE_URL}software/{name}/index.html)'
              for name, p in PROJECTS.items()]
    (pathlib.Path(app.outdir) / 'llms.txt').write_text('\n'.join(lines) + '\n')


def setup(app):
    if not _ARCHIVE:
        mount.patch_relfn2path(MOUNT, PROJECTS)
    # Before the theme reads theme_switcher at the default priority (500).
    app.connect('html-page-context', _page_context, priority=400)
    app.connect('build-finished', _write_versions)
    app.connect('build-finished', _write_llms_txt)
